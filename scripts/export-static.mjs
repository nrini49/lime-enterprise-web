#!/usr/bin/env node
/**
 * Copy the built site into dist/ as plain static files, ready to upload to any host
 * (GoDaddy later), with no build step and nothing Vercel-specific required.
 *   npm run build && npm run export   →   dist/
 * dist/ is gitignored. It holds the four pages, the Harbor Now editions, the sample-data
 * demo and the assets, plus an .htaccess that repeats vercel.json's redirects for Apache
 * hosts. Nothing here uploads anything; the upload is a separate, manual step.
 */
import { cp, rm, mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'dist');
const SHIP = ['index.html', 'how-rosie-works', 'harbor-now', 'blog', 'rosie-demo', 'assets'];

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
for (const item of SHIP) await cp(path.join(root, item), path.join(out, item), { recursive: true });

// vercel.json redirects → Apache mod_alias lines (exact paths; ":path*" becomes a prefix match).
const { redirects = [] } = JSON.parse(await readFile(path.join(root, 'vercel.json'), 'utf8'));
const lines = redirects.map((r) => {
  const code = r.permanent ? 301 : 302;
  if (r.source.includes(':path*')) {
    const prefix = r.source.replace('/:path*', '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    return `RedirectMatch ${code} ^${prefix}(/.*)?$ ${r.destination}`;
  }
  return `RedirectMatch ${code} ^${r.source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}/?$ ${r.destination}`;
});
await writeFile(
  path.join(out, '.htaccess'),
  ['# Generated by scripts/export-static.mjs from vercel.json. Apache hosts only.', 'DirectoryIndex index.html', ...lines, ''].join('\n'),
);
console.log(`exported ${SHIP.join(', ')} and .htaccess (${lines.length} redirects) to dist/`);
